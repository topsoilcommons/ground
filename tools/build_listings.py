#!/usr/bin/env python3
"""Build the take away listings.json at the Ground site root.

One file, two jobs, one source for each part:

- The seed board for New Rochelle and nearby Westchester is kept in
  listings.json itself. Its entries are the ones whose slug is
  "new-rochelle-ny"; on a file that predates this tool they are the
  whole listings list. The page on this site renders only those entries.
- Every other entry in listings.json is generated here from the place
  files under places/, in the order places/index.json lists them. Do
  not edit those entries in listings.json; edit the place file and
  rerun this tool.

Each listing keeps its own fields and gains its place and its slug, so
the file holds every Ground listing with its checked date, its expiry
date, and its provider source in one place an agent can take away.

Run: python3 tools/build_listings.py
Use --check to compare the committed file with a fresh build.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED_PLACE = "New Rochelle and nearby Westchester"
SEED_SLUG = "new-rochelle-ny"


def load_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def seed_parts(data):
    """Split a listings.json into its kept seed board and its heading."""
    listings = data["listings"]
    if any("slug" in listing for listing in listings):
        seed = []
        for listing in listings:
            if listing.get("slug") != SEED_SLUG:
                continue
            kept = {key: value for key, value in listing.items()
                    if key not in ("place", "slug")}
            seed.append(kept)
        board = data["board"]
        for place in data.get("places", []):
            if place.get("slug") == SEED_SLUG:
                board = place["board"]
        return seed, board
    return listings, data["board"]


def build():
    current = load_json(ROOT / "listings.json")
    seed, seed_board = seed_parts(current)
    if not seed:
        print("build_listings: no seed board entries found", file=sys.stderr)
        sys.exit(1)

    places_index = load_json(ROOT / "places" / "index.json")
    listings = []
    for listing in seed:
        entry = dict(listing)
        entry["place"] = SEED_PLACE
        entry["slug"] = SEED_SLUG
        listings.append(entry)

    places = [{
        "board": seed_board,
        "expires": seed[0]["expires"],
        "file": "listings.json",
        "listings": len(seed),
        "place": SEED_PLACE,
        "slug": SEED_SLUG,
        "verified_on": current["verified_on"],
    }]
    for place in places_index["places"]:
        data = load_json(ROOT / place["file"])
        if data["slug"] != place["slug"]:
            print("build_listings: slug mismatch in %s" % place["file"],
                  file=sys.stderr)
            sys.exit(1)
        if len(data["listings"]) != place["listings"]:
            print("build_listings: count mismatch in %s" % place["file"],
                  file=sys.stderr)
            sys.exit(1)
        for listing in data["listings"]:
            entry = dict(listing)
            entry["place"] = data["place"]
            entry["slug"] = data["slug"]
            listings.append(entry)
        places.append(place)

    for listing in listings:
        for field in ("verified", "expires", "source"):
            if not listing.get(field):
                print("build_listings: listing %s has no %s"
                      % (listing.get("id"), field), file=sys.stderr)
                sys.exit(1)
    ids = [listing["id"] for listing in listings]
    if len(ids) != len(set(ids)):
        print("build_listings: duplicate listing ids", file=sys.stderr)
        sys.exit(1)

    combined = {
        "board": "Ground: verified local resources, all places",
        "expiry_rule": current["expiry_rule"],
        "generated_by": "tools/build_listings.py",
        "listings": listings,
        "places": places,
        "source_note": (
            "The seed board entries, slug new-rochelle-ny, are kept in "
            "this file. Every other entry is generated by "
            "tools/build_listings.py from its place file under places/. "
            "Edit the source, not the generated entry."),
        "verified_on": current["verified_on"],
        "verifier": current["verifier"],
    }
    return json.dumps(combined, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False)


def main(argv):
    rendered = build()
    path = ROOT / "listings.json"
    if "--check" in argv:
        if path.read_text(encoding="utf-8") != rendered:
            print("FAIL listings.json: it differs from the source data")
            return 1
        data = json.loads(rendered)
        print("PASS listings.json: %d listings across %d places"
              % (len(data["listings"]), len(data["places"])))
        return 0
    path.write_text(rendered, encoding="utf-8")
    data = json.loads(rendered)
    print("build_listings: %d listings across %d places"
          % (len(data["listings"]), len(data["places"])))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
