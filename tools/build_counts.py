#!/usr/bin/env python3
"""Build the counts section of the Ground home page from the data files.

The counts come from the same files the board itself reads: the seed
board entries in listings.json and places/index.json for the other
boards. Nothing in the section is typed by hand. Run this after a board
changes, and commit the page it writes.

The page is a snapshot of the verified set. Its counted date and its
freshness band are measured at the check date recorded in the data, not
at the wall clock, so rebuilding the page on a later day writes the same
page until the data itself changes.

The surface section keeps the human story only: the counts, the tables,
and the freshness band with its printed key. The builder record (the file
names, the check log, and how the counts are made) is generated into the
closing "For agents and builders" section, between the counts-tech
markers.

Run: python3 tools/build_counts.py
"""

import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- counts:begin -->"
END = "<!-- counts:end -->"
TECH_BEGIN = "<!-- counts-tech:begin -->"
TECH_END = "<!-- counts-tech:end -->"


def fmt_date(value):
    parsed = date.fromisoformat(value)
    return parsed.strftime("%B %-d, %Y")


def main():
    seed = json.loads((ROOT / "listings.json").read_text(encoding="utf-8"))
    places_data = json.loads(
        (ROOT / "places" / "index.json").read_text(encoding="utf-8"))

    # listings.json is the combined take away file built by
    # tools/build_listings.py. The board on this page is its seed board:
    # the entries whose slug names New Rochelle. A file that predates
    # the combined build carries no slugs, and all of it is the seed.
    seed_listings = [l for l in seed["listings"]
                     if l.get("slug") in (None, "new-rochelle-ny")]
    rows = []
    categories = Counter()
    seed_count = len(seed_listings)
    categories.update(l["category"] for l in seed_listings)
    rows.append(("New Rochelle and nearby Westchester", seed_count,
                 seed["verified_on"], seed_listings[0]["expires"]))
    for place in places_data["places"]:
        categories.update(place["categories"])
        rows.append((place["place"], place["listings"],
                     place["verified_on"], place["expires"]))
    total = sum(r[1] for r in rows)

    verified = rows[0][2]
    expires = rows[0][3]
    start = date.fromisoformat(verified)
    end = date.fromisoformat(expires)
    today = start
    span = (end - start).days
    elapsed = min(max((today - start).days, 0), span)
    fraction = (elapsed / span) if span else 0

    place_rows = "\n".join(
        "<tr><td>%s</td><td>%d</td><td>%s</td><td>%s</td></tr>"
        % (name, count, fmt_date(v), fmt_date(e))
        for name, count, v, e in rows)
    cat_rows = "\n".join(
        "<tr><td>%s</td><td>%d</td></tr>" % (name.capitalize(), count)
        for name, count in sorted(categories.items(),
                                  key=lambda kv: (-kv[1], kv[0])))
    section = """%s
<section aria-labelledby="counts-h">
  <h2 id="counts-h">Ground in numbers</h2>
  <p class="sub">%d listings stand checked across %d places, counted on %s. Every listing was checked on %s and is due a fresh check on %s.</p>
  <table class="counts-table">
    <thead><tr><th scope="col">Place</th><th scope="col">Listings</th><th scope="col">Checked</th><th scope="col">Check again</th></tr></thead>
    <tbody>
%s
    </tbody>
  </table>
  <table class="counts-table">
    <thead><tr><th scope="col">Kind of help</th><th scope="col">Listings</th></tr></thead>
    <tbody>
%s
    </tbody>
  </table>
  <p class="sub">How fresh the board is, as one band:</p>
  <div class="freshband" role="img" aria-label="Freshness band: %d of %d days passed between the check date and the recheck date."><i style="--scale:%.4f"></i></div>
  <p class="sub">Key: the band runs from the check date, %s, to the recheck date, %s. The filled part is the share of that span that has passed by today, %s. One unit is one day, and the full span is %d days.</p>
</section>
%s""" % (BEGIN, total, len(rows), fmt_date(verified), fmt_date(verified),
         fmt_date(expires), place_rows, cat_rows, elapsed, span, fraction,
         fmt_date(verified), fmt_date(expires), fmt_date(today.isoformat()),
         span, END)

    tech = """%s
<h3>How the counts and the checks are recorded</h3>
<p>Generated by tools/build_counts.py. The counts come from the seed board entries in listings.json for the board on this page and places/index.json for the other places, both in this repository. Nothing in the counts section is typed by hand.</p>
<p>Each listing in listings.json carries its provider page in its source field, the date it was checked in its verified field, and the date to check again in its expires field, 30 days after the check. The public log of checks is checks.json in this repository: a check adds a row with the checker's name, stage name, or handle, and the new verified and expires dates. Full places record: PLACES.md in this repository. Full steps for checking a listing: the README of this repository, under Verify a listing.</p>
<p>Take away data: listings.json at this site root holds every Ground listing in one file, %d listings across %d places, each with its fields, its checked date, its expiry date, and its provider source. tools/build_listings.py builds that file from the seed board entries it keeps and the place files under places/, so the file and this page come from the same data.</p>
<p>The sample Proof on this page is the listing with the record name hope-food-pantry in listings.json, and its check is logged in checks.json.</p>
%s""" % (TECH_BEGIN, total, len(rows), TECH_END)

    path = ROOT / "index.html"
    page = path.read_text(encoding="utf-8")
    if TECH_BEGIN not in page or TECH_END not in page:
        print("build_counts: counts-tech markers not found", file=sys.stderr)
        sys.exit(1)
    tbefore, trest = page.split(TECH_BEGIN, 1)
    _, tafter = trest.split(TECH_END, 1)
    page = tbefore + tech + tafter
    if BEGIN in page and END in page:
        before, rest = page.split(BEGIN, 1)
        _, after = rest.split(END, 1)
        page = before + section + after
    else:
        anchor = '<section>\n  <h2>One listing, as a full Proof</h2>'
        if anchor not in page:
            print("build_counts: insertion anchor not found",
                  file=sys.stderr)
            sys.exit(1)
        page = page.replace(anchor, section + "\n\n" + anchor, 1)
    path.write_text(page, encoding="utf-8")
    print("build_counts: %d listings across %d places" % (total, len(rows)))


if __name__ == "__main__":
    main()
